// Regenerates src/theme/fluent-emoji-glyphs.ts, the bundled subset of Microsoft's Fluent Emoji
// Flat (MIT). Developer tool, not part of the build:
//
//   npm pack @iconify-json/fluent-emoji-flat   (in a scratch folder, then untar)
//   node scripts/generate-fluent-emoji.js <path to package/icons.json> <path to a map json>
//
// The map is { "<ionicons glyph, no -outline suffix>": "<fluent emoji name>" }. Only emoji built
// from plain shapes (path, circle, ellipse, rect, group) with simple paint attributes are kept, so
// they render through react-native-svg on every platform without gradients, filters or clip paths.
// The source of truth for the shipped mapping is the generated file itself.
const fs = require("fs");

const [iconsPath, mapPath, outPath] = process.argv.slice(2);
const icons = JSON.parse(fs.readFileSync(iconsPath, "utf8")).icons;
const map = JSON.parse(fs.readFileSync(mapPath, "utf8"));

const ALLOWED = new Set([
  "fill",
  "d",
  "fill-rule",
  "cx",
  "cy",
  "r",
  "rx",
  "ry",
  "x",
  "y",
  "width",
  "height",
  "opacity",
]);

function parse(body) {
  if (
    /<(defs|clipPath|use|filter|linearGradient|radialGradient|mask)/.test(body)
  )
    return null;
  const shapes = [];
  const tag = /<(path|circle|ellipse|rect)\s([^>]*?)\/?>/g;
  let match;
  while ((match = tag.exec(body))) {
    const attrs = {};
    for (const a of match[2].matchAll(/([a-z-]+)="([^"]*)"/g)) {
      if (!ALLOWED.has(a[1])) return null;
      attrs[a[1]] = a[2];
    }
    if (/<g\s[^>]*(transform|clip|opacity)/.test(body)) return null;
    shapes.push({ t: match[1], a: attrs });
  }
  return shapes.length ? shapes : null;
}

const emojis = {};
const byIon = {};
const dropped = [];
for (const [ion, name] of Object.entries(map)) {
  if (!icons[name]) {
    dropped.push(`${ion} -> ${name} (missing)`);
    continue;
  }
  if (!(name in emojis)) {
    const shapes = parse(icons[name].body);
    if (!shapes) {
      dropped.push(`${ion} -> ${name} (unsupported paint)`);
      continue;
    }
    emojis[name] = shapes;
  }
  byIon[ion] = name;
}

const header = `// GENERATED by scripts/generate-fluent-emoji.js. Do not edit by hand.
// Microsoft Fluent Emoji Flat, MIT License, Copyright (c) Microsoft Corporation.
// https://github.com/microsoft/fluentui-emoji (see THIRD_PARTY_NOTICES.md).
// 32x32 viewBox; each emoji is a list of plain SVG shapes carrying their own colors.

export type FluentShape = { t: "path" | "circle" | "ellipse" | "rect"; a: Record<string, string> };

`;
let out = header;
out +=
  "// prettier-ignore\nexport const FLUENT_EMOJI: Readonly<Record<string, readonly FluentShape[]>> = {\n";
for (const [name, shapes] of Object.entries(emojis))
  out += `  ${JSON.stringify(name)}: ${JSON.stringify(shapes)},\n`;
out += "};\n\n";
out +=
  "// prettier-ignore\nexport const FLUENT_EMOJI_BY_ION: Readonly<Record<string, string>> = " +
  JSON.stringify(byIon, null, 2) +
  ";\n";
fs.writeFileSync(outPath, out);
console.log(
  `emoji: ${Object.keys(emojis).length}, ion ids: ${Object.keys(byIon).length}`,
);
console.log("dropped:", dropped.join("; "));
